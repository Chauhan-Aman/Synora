import React from 'react';

interface ProceduralCoverProps {
  title: string;
  theme?: 'dark' | 'light';
  gradient?: string;
  patternOpacity?: number;
  mood?: string;
  className?: string;
}

export function ProceduralCover({
  title,
  theme = 'dark',
  gradient = 'linear-gradient(135deg, #1e293b 0%, #0f172a 100%)',
  patternOpacity = 0.1,
  mood = 'Default',
  className = ''
}: ProceduralCoverProps) {
  
  // A subtle dot pattern SVG encoded for background
  const dotPattern = `url("data:image/svg+xml,%3Csvg width='20' height='20' viewBox='0 0 20 20' xmlns='http://www.w3.org/2000/svg'%3E%3Cg fill='%23${theme === 'dark' ? 'ffffff' : '000000'}' fill-opacity='${patternOpacity}' fill-rule='evenodd'%3E%3Ccircle cx='3' cy='3' r='1'/%3E%3Ccircle cx='13' cy='13' r='1'/%3E%3C/g%3E%3C/svg%3E")`;
  
  const textColor = theme === 'dark' ? 'text-white' : 'text-slate-900';
  const subtitleColor = theme === 'dark' ? 'text-slate-300' : 'text-slate-600';

  return (
    <div 
      className={`relative w-full aspect-video rounded-2xl overflow-hidden shadow-2xl flex flex-col justify-end p-8 md:p-12 ${className}`}
      style={{ background: gradient }}
    >
      {/* Pattern Overlay */}
      <div 
        className="absolute inset-0 pointer-events-none mix-blend-overlay"
        style={{ backgroundImage: dotPattern }}
      />
      
      {/* Vignette / Shadow Overlay to ensure text readability */}
      <div className={`absolute inset-0 bg-gradient-to-t ${theme === 'dark' ? 'from-black/60' : 'from-white/60'} via-transparent to-transparent pointer-events-none`} />

      {/* Content */}
      <div className="relative z-10 w-full max-w-4xl">
        <div className="flex items-center gap-3 mb-4">
          <div className={`px-3 py-1 rounded-full text-xs font-bold uppercase tracking-wider backdrop-blur-md ${theme === 'dark' ? 'bg-white/10 text-white' : 'bg-black/10 text-black'}`}>
            {mood}
          </div>
          <div className={`h-px flex-1 opacity-20 ${theme === 'dark' ? 'bg-white' : 'bg-black'}`}></div>
        </div>
        
        <h1 className={`text-3xl md:text-5xl lg:text-6xl font-bold leading-tight ${textColor} mb-4 drop-shadow-lg`}>
          {title}
        </h1>
        
        <p className={`text-sm md:text-base font-medium ${subtitleColor} drop-shadow-md`}>
          Generated by Synora AI
        </p>
      </div>
    </div>
  );
}
